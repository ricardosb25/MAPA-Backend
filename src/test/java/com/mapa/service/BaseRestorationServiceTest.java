package com.mapa.service;

import com.mapa.domain.User;
import com.mapa.domain.enums.Role;
import com.mapa.domain.enums.UserAuditAction;
import com.mapa.exception.BaseRestorationException;
import com.mapa.repository.ChallengeRepository;
import com.mapa.security.UserPrincipal;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

class BaseRestorationServiceTest {
    private JdbcTemplate jdbcTemplate;
    private TransactionTemplate transactionTemplate;
    private ChallengeRepository challengeRepository;
    private UserAuditLogService auditLogService;
    private BaseRestorationService restorationService;

    @BeforeEach
    void prepareDatabase() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:restore-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbcTemplate = new JdbcTemplate(dataSource);
        transactionTemplate = new TransactionTemplate(new DataSourceTransactionManager(dataSource));
        challengeRepository = mock(ChallengeRepository.class);
        auditLogService = mock(UserAuditLogService.class);
        restorationService = new BaseRestorationService(dataSource, jdbcTemplate, challengeRepository, auditLogService);
        jdbcTemplate.execute("""
                CREATE TABLE motors (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  manufacturer VARCHAR(50) NOT NULL, name VARCHAR(50) NOT NULL, description VARCHAR(255),
                  displacement_liters NUMERIC(3,1) NOT NULL, displacement_cc INT NOT NULL,
                  compression_ratio NUMERIC(4,1) NOT NULL, rpm_cutoff INT NOT NULL,
                  aspiration_type VARCHAR(20) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL)
                """);
        jdbcTemplate.execute("CREATE TABLE users (id BIGINT PRIMARY KEY, active_motor_id BIGINT)");
        jdbcTemplate.execute("CREATE TABLE ecu_map_tunings (id BIGINT PRIMARY KEY, motor_id BIGINT)");
        jdbcTemplate.execute("""
                CREATE TABLE ecu_map_defaults (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  displacement_class NUMERIC(3,1) NOT NULL, map_type VARCHAR(20) NOT NULL,
                  rpm_breakpoints VARCHAR(2000) NOT NULL, load_breakpoints VARCHAR(1000) NOT NULL,
                  factory_values VARCHAR(4000) NOT NULL,
                  created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
                  UNIQUE(displacement_class, map_type))
                """);
        jdbcTemplate.update("""
                INSERT INTO motors (manufacturer, name, displacement_liters, displacement_cc,
                  compression_ratio, rpm_cutoff, aspiration_type, created_at)
                VALUES ('CUSTOM', 'Custom motor', 1.0, 1000, 10.0, 6000, 'ASPIRADO', CURRENT_TIMESTAMP)
                """);
        jdbcTemplate.update("INSERT INTO users VALUES (1, 1)");
        jdbcTemplate.update("INSERT INTO ecu_map_tunings VALUES (1, 1)");
        authenticate(Role.ADMIN);
    }

    @AfterEach
    void cleanUpDatabase() {
        SecurityContextHolder.clearContext();
        jdbcTemplate.execute("SHUTDOWN");
    }

    @Test
    void shouldReplaceMotorsAndClearSelectionsAndTunings() {
        transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMotors());
        assertEquals(6, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM motors", Integer.class));
        assertEquals(0, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM motors WHERE manufacturer = 'CUSTOM'", Integer.class));
        assertNull(jdbcTemplate.queryForObject("SELECT active_motor_id FROM users WHERE id = 1", Long.class));
        assertEquals(0, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM ecu_map_tunings", Integer.class));
        verify(auditLogService).recordRequiredByCurrentUser(eq(UserAuditAction.MOTOR_BASE_RESTORED), anyString());
    }

    @Test
    void shouldNotDuplicateMotorsOnRepeatedRestoration() {
        transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMotors());
        transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMotors());
        assertEquals(6, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM motors", Integer.class));
    }

    @Test
    void shouldBlockMotorRestorationWithChallenges() {
        when(challengeRepository.count()).thenReturn(1L);
        assertThrows(BaseRestorationException.class,
                () -> transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMotors()));
        assertEquals(1, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM motors", Integer.class));
        assertEquals(1L, jdbcTemplate.queryForObject("SELECT active_motor_id FROM users WHERE id = 1", Long.class));
        verifyNoInteractions(auditLogService);
    }

    @Test
    void shouldReplaceMapsAndClearAllTunings() {
        transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMaps());
        jdbcTemplate.update("UPDATE ecu_map_defaults SET factory_values = '[[999]]'");
        transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMaps());
        assertEquals(20, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM ecu_map_defaults", Integer.class));
        assertEquals(0, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM ecu_map_defaults WHERE factory_values = '[[999]]'", Integer.class));
        assertEquals(0, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM ecu_map_tunings", Integer.class));
        assertEquals(1, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM motors", Integer.class));
        verify(auditLogService, times(2)).recordRequiredByCurrentUser(eq(UserAuditAction.ECU_MAP_BASE_RESTORED), anyString());
    }

    @Test
    void shouldRollbackDeletionAndSeedWhenAuditFails() {
        doThrow(new IllegalStateException("Audit unavailable")).when(auditLogService)
                .recordRequiredByCurrentUser(any(), anyString());
        assertThrows(IllegalStateException.class,
                () -> transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMotors()));
        assertEquals(1, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM motors", Integer.class));
        assertEquals("CUSTOM", jdbcTemplate.queryForObject("SELECT manufacturer FROM motors", String.class));
        assertEquals(1L, jdbcTemplate.queryForObject("SELECT active_motor_id FROM users WHERE id = 1", Long.class));
        assertEquals(1, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM ecu_map_tunings", Integer.class));
    }

    @Test
    void shouldRejectStudentAndTeacherRestoration() {
        for (Role role : List.of(Role.STUDENT, Role.TEACHER)) {
            authenticate(role);
            assertThrows(AccessDeniedException.class, () -> restorationService.restoreMotors());
            assertThrows(AccessDeniedException.class, () -> restorationService.restoreMaps());
        }
        verifyNoInteractions(challengeRepository, auditLogService);
        assertEquals(1, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM motors", Integer.class));
    }

    @Test
    void shouldRollbackWhenSeedFails() {
        jdbcTemplate.execute("ALTER TABLE motors ADD CONSTRAINT custom_manufacturer_only CHECK (manufacturer = 'CUSTOM')");
        assertThrows(org.springframework.dao.DataAccessException.class,
                () -> transactionTemplate.executeWithoutResult(transactionStatus -> restorationService.restoreMotors()));
        assertEquals("CUSTOM", jdbcTemplate.queryForObject("SELECT manufacturer FROM motors", String.class));
        assertEquals(1L, jdbcTemplate.queryForObject("SELECT active_motor_id FROM users WHERE id = 1", Long.class));
        assertEquals(1, jdbcTemplate.queryForObject("SELECT COUNT(*) FROM ecu_map_tunings", Integer.class));
        verifyNoInteractions(auditLogService);
    }

    private void authenticate(Role role) {
        User account = User.builder().id(1L).fullName("Test account").email("test@mapa.test")
                .passwordHash("unused-test-hash").active(true).role(role).build();
        SecurityContextHolder.getContext().setAuthentication(new UsernamePasswordAuthenticationToken(
                new UserPrincipal(account), null, List.of()));
    }
}
